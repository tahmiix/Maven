package org.codewiththamsanqa;

public class Student {
    public int id;
    public String name;

    public Student(int id, String name) {

    }

    public String getName() {
        return name;
    }

    public int getId() {
        return id;
    }

    public void setId(int id) {
        this.id = id;
    }

    public void setName(String name) {
        this.name = name;
    }
}
